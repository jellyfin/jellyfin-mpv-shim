class SentinelReachingAWriteTest(unittest.TestCase):
    """`ANY_SERVER` is truthy, so a guard written for two values lets it past.

    The sentinel exists to say "every server" out loud where a falsy value used
    to mean it. It was made truthy so that `if server_id:` kept reading as "a
    scope was asked for" -- but a predicate can equally have meant "I hold a
    real server identity", and no boolean value serves both. These are the two
    sites where that difference is observable; the class is named after the
    shared cause rather than after either, because the next one will be a third
    site of the same kind and not a new bug.
    """

    def setUp(self):
        self.dir = tempfile.mkdtemp()
        self.addCleanup(shutil.rmtree, self.dir, ignore_errors=True)
        self.db = SyncDB(os.path.join(self.dir, "catalog.db"))
        self.addCleanup(self.db.close)
        # `list_playlists` only answers for a playlist holding a COMPLETE
        # item, so a membership is part of the fixture rather than of what
        # is under test. Without it the assertions pass over an empty list
        # and the write could have failed unnoticed.
        self.db.upsert({"item_id": "film", "content_server_id": SERVER,
                        "status": STATUS_COMPLETE})
        # `server_id=None` to match the row the tests below write: this class
        # is about the *unscoped* ask, and NULL is its representable form.
        self.db.replace_playlist_items("pl", [("film", 0, 1)], server_id=None)

    def test_a_playlist_asked_for_unscoped_is_written_not_raised(self):
        """`server_id or None` passes the sentinel object itself to sqlite,
        which has no adapter for it and raises `ProgrammingError` -- so the
        whole playlist write is lost, not merely mis-scoped."""
        self.db.upsert_playlist("pl", ANY_SERVER, "uuid-a", "Example Playlist")
        row = self.db.list_playlists()
        self.assertEqual(1, len(row),
                         "the unscoped playlist write did not land at all")
        self.assertIsNone(
            row[0]["server_id"],
            "an unscoped ask must land as NULL -- the representable 'we could "
            "not tell', which `list_playlists` answers for")

    def test_no_column_of_an_unscoped_playlist_holds_the_sentinel(self):
        """The general form, so the value cannot reappear in a second column.

        The sentinel is passed only where a *scope* belongs. It is deliberately
        NOT passed as `server_uuid`: that parameter names a saved login, so a
        sentinel arriving there is a caller error, and normalising it would hide
        the bug instead of the value.
        """
        self.db.upsert_playlist("pl", ANY_SERVER, "uuid-a", "Example")
        for row in self.db.list_playlists():
            for key in row.keys():
                self.assertNotIsInstance(
                    row[key], type(ANY_SERVER),
                    "%s stored the sentinel object itself" % key)

    def test_a_client_that_will_not_resolve_claims_no_route(self):
        """`_connected_routes` keys by `content_id_for`'s answer, and the
        sentinel is truthy -- so a client whose login cannot be resolved was
        filed under "the server called ANY_SERVER" and then answered as *a*
        route. No longer inert: `routes_for` is looked up per download row,
        which is why `routes_for` refuses the sentinel on the way in as well.
        """
        mgr = SyncManager()

        class _Client:
            pass

        # `get_clients` is an instance attribute injected by `start`, not a
        # method -- patching the class raises AttributeError, which is a test
        # that cannot fail for its stated reason.
        mgr.get_clients = lambda: {"login-broken": _Client()}
        with mock.patch.object(SyncManager, "content_id_for",
                               staticmethod(lambda uuid: ANY_SERVER)):
            routes = mgr._connected_routes()
        self.assertEqual(
            {}, routes,
            "an unresolvable client was given a route under the sentinel; "
            "routes are keyed by a real ServerId or they are not routes")


